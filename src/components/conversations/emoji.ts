export const EMOJI_GROUPS: { title: string; emoji: Emoji[] }[] = GROUPS.map(([title, rows]) => ({
  title,
  emoji: rows.map(([char, name, keywords = ""]) => ({ char, name, keywords })),
}));

const ALL = EMOJI_GROUPS.flatMap((group) => group.emoji);

/*
 * The emoji a search finds: the one it names exactly, those whose shortcode starts with it, then
 * those with it anywhere in the shortcode or their words. "thu" finds 👍 by
 * its word "thumbsup".
 */
export function searchEmoji(query: string, limit = Infinity) {
  const q = query.trim().toLowerCase().replace(/^:|:$/g, "");
  if (!q) return ALL.slice(0, limit);
  const starts = ALL.filter((emoji) => emoji.name.startsWith(q)).sort(
    (a, b) => Number(b.name === q) - Number(a.name === q),
  );
  const contains = ALL.filter(
    (emoji) =>
      !emoji.name.startsWith(q) && `${emoji.name.replace(/_/g, " ")} ${emoji.keywords}`.includes(q),
  );
  return [...starts, ...contains].slice(0, limit);
}
